export function normalizeLocale(value: unknown): Locale {
  return String(value ?? defaultLocale)
    .toLowerCase()
    .startsWith("en")
    ? "en-US"
    : "zh-CN";
}

export function resolveLocale(locale = defaultLocale): keyof typeof dictionaries {
  return locale.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function getUiLocale(): Locale {
  return currentLocale;
}

export function setUiLocale(locale: unknown): Locale {
  currentLocale = normalizeLocale(locale);
  try {
    window.localStorage.setItem("mangavault.locale", currentLocale);
  } catch {
    // Storage can be unavailable in tests or hardened browser contexts.
  }
  for (const listener of listeners) listener();
  return currentLocale;
}

export function subscribeLocale(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function t(key: TranslationKey, locale = currentLocale): string {
  return dictionaries[resolveLocale(locale)][key];
}

export function formatUserError(error: unknown, locale = currentLocale): string {
  const raw = error instanceof Error ? error.message : String(error ?? "");
  const message = raw.replace(/^Error:\s*/i, "").trim();
  const lower = message.toLowerCase();
  if (lower.includes("database lock poisoned") || lower.includes("database busy")) {
    return t("errorDatabaseBusy", locale);
  }
  if (lower.includes("page unavailable")) return t("errorPageUnavailable", locale);
  if (lower === "invalid path" || lower.includes("path does not exist")) {
    return t("errorInvalidPath", locale);
  }
  const prefixedErrors: Array<[string, TranslationKey]> = [
    ["unsupported format:", "errorUnsupportedFormat"],
    ["external extractor unavailable for", "errorExtractorUnavailable"],
    ["database error:", "errorDatabase"],
    ["io error:", "errorFileAccess"],
    ["zip error:", "errorArchive"],
    ["image error:", "errorImage"],
    ["pdf error:", "errorPdf"],
  ];
  for (const [prefix, key] of prefixedErrors) {
    if (!lower.startsWith(prefix)) continue;
    const detail = message.slice(prefix.length).trim();
    const separator = resolveLocale(locale) === "zh" ? "：" : ": ";
    return detail ? `${t(key, locale)}${separator}${detail}` : t(key, locale);
  }
  if (!message) return t("appCrashedTitle", locale);
  return resolveLocale(locale) === "zh" ? t("errorUnexpected", locale) : message;
}

function readStoredLocale(): Locale {
  try {
    return normalizeLocale(window.localStorage.getItem("mangavault.locale"));
  } catch {
    return defaultLocale;
  }
}
